#!/usr/bin/env node
import { readdirSync, statSync, readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs'
import { join, resolve, dirname, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const rootDir = resolve(__dirname, '..')
const scenesDir = join(rootDir, 'scenes')
const lobbyDir = join(scenesDir, 'lobby')
const outDir = join(lobbyDir, 'src', 'generated')
const outFile = join(outDir, 'demos.ts')

const LOBBY = 'lobby'

const parseParcel = (s) => {
  const [x, y] = s.split(',').map((n) => Number.parseInt(n.trim(), 10))
  if (!Number.isFinite(x) || !Number.isFinite(y)) {
    throw new Error(`invalid parcel string: "${s}"`)
  }
  return { x, y }
}

const averageRange = (v) => {
  if (Array.isArray(v)) {
    if (v.length === 0) return 0
    const sum = v.reduce((a, b) => a + b, 0)
    return sum / v.length
  }
  return v
}

const sceneDirs = existsSync(scenesDir)
  ? readdirSync(scenesDir).filter((entry) => {
      if (entry === LOBBY) return false
      const p = join(scenesDir, entry)
      return statSync(p).isDirectory() && existsSync(join(p, 'scene.json'))
    })
  : []

const demos = sceneDirs
  .map((scene) => {
    const sceneJsonPath = join(scenesDir, scene, 'scene.json')
    const raw = readFileSync(sceneJsonPath, 'utf8')
    let json
    try {
      json = JSON.parse(raw)
    } catch (e) {
      throw new Error(`failed to parse ${relative(rootDir, sceneJsonPath)}: ${e.message}`)
    }

    const title = json?.display?.title ?? scene
    const description = json?.display?.description ?? ''
    const baseStr = json?.scene?.base
    const parcels = Array.isArray(json?.scene?.parcels) ? json.scene.parcels : []
    if (!baseStr || parcels.length === 0) {
      throw new Error(`${relative(rootDir, sceneJsonPath)} is missing scene.base or scene.parcels`)
    }
    const base = parseParcel(baseStr)

    const spawn = Array.isArray(json?.spawnPoints) ? json.spawnPoints[0] : undefined
    const spawnX = spawn?.position?.x !== undefined ? averageRange(spawn.position.x) : base.x * 16 + 8
    const spawnZ = spawn?.position?.z !== undefined ? averageRange(spawn.position.z) : base.y * 16 + 8

    return {
      scene,
      title,
      description,
      base,
      parcels: parcels.length,
      spawn: { x: spawnX, z: spawnZ }
    }
  })
  .sort((a, b) => (a.base.x - b.base.x) || (a.base.y - b.base.y))

mkdirSync(outDir, { recursive: true })

const banner = `// AUTO-GENERATED by scripts/generate-lobby-demos.mjs — DO NOT EDIT.
// Source: scenes/*/scene.json (excluding "${LOBBY}").
// Regenerate with: npm run generate-lobby-demos
`

const body = `export type DemoParcel = { x: number; y: number }

export type Demo = {
  /** Folder name under scenes/. */
  scene: string
  /** display.title from scene.json. */
  title: string
  /** display.description from scene.json. */
  description: string
  /** Base parcel (parcel grid coords). */
  base: DemoParcel
  /** Number of parcels the scene occupies. */
  parcels: number
  /** Absolute world position of the default spawn point (metres). */
  spawn: { x: number; z: number }
}

export const DEMOS: Demo[] = ${JSON.stringify(demos, null, 2)}
`

const content = `${banner}\n${body}`
writeFileSync(outFile, content)

console.log(`✓ wrote ${relative(rootDir, outFile)} (${demos.length} demo${demos.length === 1 ? '' : 's'})`)
for (const d of demos) {
  console.log(`  · ${d.scene} — parcel ${d.base.x},${d.base.y} → spawn (${d.spawn.x}, ${d.spawn.z})`)
}
